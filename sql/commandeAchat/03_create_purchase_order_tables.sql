--   - pre_accounting_id en varchar(20) (NUMBER dans la spec, codes alphanumeriques) ;
--   - THIRD_PARTY_EMISSION_DESC, en double dans PURCHASE_ORDER_LINE_NOPART, une seule fois.
--
-- Tables SNAPSHOT : videes et rechargees par clean_data.alimenter_purchase_order()
-- (04_alimenter_purchase_order.sql) depuis clean_data.commande_achat_ifs.
-- DROP + CREATE : aucune donnee a preserver.
-- ============================================================================

