    pays_fournisseur_principal VARCHAR(20),
    ville_fournisseur_principal VARCHAR(35),
    actif_dans_centre TEXT,
    actif_commercial TEXT,
    actif_evaluation TEXT,
    actif_achat TEXT,
    avec_stock TEXT,
    statut_utilisation TEXT,
    date_creation VARCHAR(20),
    createur VARCHAR(20),
    date_modification VARCHAR(20),
    modificateur VARCHAR(20),
    langue VARCHAR(20),
    codification_id VARCHAR(25)
);

COMMENT ON TABLE clean_data.ifs_article_maitre IS 'Table des articles maîtres pour migration vers IFS';
