    nombre_centres_actifs BIGINT,
    centres_list TEXT,
    groupes_achat_list TEXT,
    strategies_list TEXT,
    stock_minimum_total NUMERIC,
    stock_securite_total NUMERIC,
    stock_maximum_total NUMERIC,
    avec_gestion_lot TEXT,
    profils_serie_list TEXT,
