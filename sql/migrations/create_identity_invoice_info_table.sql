    CREATED_BY VARCHAR(100),
    UPDATED_BY VARCHAR(100),
    IS_DELETED BOOLEAN DEFAULT FALSE,
    -- Clé primaire composite
    PRIMARY KEY (COMPANY, IDENTITY, PARTY_TYPE)
);

-- Commentaires sur la table
COMMENT ON TABLE clean_data.identity_invoice_info IS 'Table des informations de facturation des identités (fournisseurs)';

-- Commentaires sur les colonnes principales
COMMENT ON COLUMN clean_data.identity_invoice_info.COMPANY IS 'Code société';
COMMENT ON COLUMN clean_data.identity_invoice_info.IDENTITY IS 'Identifiant du fournisseur';
COMMENT ON COLUMN clean_data.identity_invoice_info.PARTY_TYPE IS 'Type de partie (Supplier, Customer, etc.)';
COMMENT ON COLUMN clean_data.identity_invoice_info.PARTY_TYPE_DB IS 'Type de partie en base (SUPPLIER, CUSTOMER, etc.)';
COMMENT ON COLUMN clean_data.identity_invoice_info.DEF_CURRENCY IS 'Devise par défaut';
COMMENT ON COLUMN clean_data.identity_invoice_info.PAYM_DEV_DAYS IS 'Délai de paiement en jours';
COMMENT ON COLUMN clean_data.identity_invoice_info.IDENTITY_TYPE_DB IS 'Type d''identité en base (EXTERN, INTERN, etc.)';
COMMENT ON COLUMN clean_data.identity_invoice_info.AUTOMATIC_INVOICE IS 'Facturation automatique (Y/N)';
COMMENT ON COLUMN clean_data.identity_invoice_info.TAX_EXEMPT IS 'Exonération fiscale (Y/N)';
COMMENT ON COLUMN clean_data.identity_invoice_info.COUNTRY_TAX_REGISTERED IS 'Enregistré fiscalement dans le pays (Y/N)';

-- Index pour améliorer les performances
CREATE INDEX IF NOT EXISTS idx_identity_invoice_info_company ON clean_data.identity_invoice_info(COMPANY);
CREATE INDEX IF NOT EXISTS idx_identity_invoice_info_identity ON clean_data.identity_invoice_info(IDENTITY);
CREATE INDEX IF NOT EXISTS idx_identity_invoice_info_party_type ON clean_data.identity_invoice_info(PARTY_TYPE);
CREATE INDEX IF NOT EXISTS idx_identity_invoice_info_created_by ON clean_data.identity_invoice_info(CREATED_BY);
CREATE INDEX IF NOT EXISTS idx_identity_invoice_info_created_timestamp ON clean_data.identity_invoice_info(CREATED_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_identity_invoice_info_is_deleted ON clean_data.identity_invoice_info(IS_DELETED);
