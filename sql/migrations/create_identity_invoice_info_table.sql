    DEF_AUTHORIZER VARCHAR(20),
    PAY_TERM_ID VARCHAR(20),
    DEF_VAT_CODE VARCHAR(20),
    ROUNDING_TAX_CODE VARCHAR(20),
    DEF_CURRENCY VARCHAR(3),
    PAYM_DEV_DAYS NUMERIC(20),
    IDENTITY_TYPE VARCHAR(4000),
    IDENTITY_TYPE_DB VARCHAR(20),
    VOTING_SHARE_PERCENTAGE VARCHAR(4000),
    VOTING_SHARE_PERCENTAGE_DB VARCHAR(20),
    DEF_PRELIMINARY_CODE VARCHAR(20),
    AUTOMATIC_INVOICE VARCHAR(1),
    PERCENT_TOLERANCE NUMERIC(20),
    AMOUNT_TOLERANCE NUMERIC(20),
    NCF_REFERENCE_CHECK VARCHAR(5),
    TAX_EXEMPT VARCHAR(5),
    TAX_EXEMPT_VALID_FROM DATE,
    TAX_EXEMPT_VALID_TO DATE,
    SECOND_TIN VARCHAR(5),
