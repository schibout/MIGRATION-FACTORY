    DEF_REC_MAN_SUPP_INV_TYPE VARCHAR(20),
    TAX_LIABILITY VARCHAR(20),
    WITHHOLDING_BASE_AMOUNT VARCHAR(4000),
    WITHHOLDING_BASE_AMOUNT_DB VARCHAR(20),
    INVOICE_RECIPIENT VARCHAR(20),
    INVOICING_SUPPLIER VARCHAR(20),
    MATCHING_LEVEL VARCHAR(4000),
    MATCHING_LEVEL_DB VARCHAR(20),
    ALLOW_TOLERANCE VARCHAR(5),
    CREATE_TOLERANCE_POSTING VARCHAR(5),
    ALLOW_QUANTITY_DIFF VARCHAR(5),
    DEFAULT_CURRENCY_RATE_TYPE VARCHAR(10),
