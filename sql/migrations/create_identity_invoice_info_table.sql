    CERTIFIED_EMAIL VARCHAR(200),
    TAX_REPRESENTATIVE VARCHAR(20),
    INC_INV_CURR_RATE_BASE VARCHAR(4000),
    INC_INV_CURR_RATE_BASE_DB VARCHAR(20),
    TAX_BUY_CURR_RATE_BASE VARCHAR(4000),
