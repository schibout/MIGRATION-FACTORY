    COMPANY VARCHAR(20),
    IDENTITY VARCHAR(20),
    PARTY_TYPE VARCHAR(4000),
    PARTY_TYPE_DB VARCHAR(20),
    INVOICE_FEE VARCHAR(5),
    EXPIRE_DATE DATE,
    NATIONAL_BANK_CODE VARCHAR(20),
