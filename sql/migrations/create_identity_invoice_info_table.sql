    PO_REF_REC_REF_VAL_METHOD VARCHAR(4000),
    PO_REF_REC_REF_VAL_METHOD_DB VARCHAR(20),
    POSTING_TEMPLATE_ID VARCHAR(10),
    LEGAL_ID_NAME VARCHAR(100),
    LEGAL_ID_ADDR_ID VARCHAR(50),
    BI_TIMESTAMP DATE,
    INVOICE_REASON_ID VARCHAR(20),
    FISCAL_NO VARCHAR(16),
